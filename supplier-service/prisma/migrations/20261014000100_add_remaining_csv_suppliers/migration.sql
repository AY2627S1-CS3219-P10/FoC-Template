SET
    "name" = 'A Hot Hideout',
    "category" = 'FOOD',
    "updated_at" = CURRENT_TIMESTAMP
WHERE "id" = '10000000-0000-4000-8000-000000000007'
  AND "name" = 'A Hot Hideout at NUS';

