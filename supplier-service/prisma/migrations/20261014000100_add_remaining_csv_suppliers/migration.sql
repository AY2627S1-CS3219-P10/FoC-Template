-- The catalog CSV was expanded from 21 to 74 suppliers.  The entries below
-- intentionally have no supplier_locations: their CSV rows omit the required
-- floor and/or coordinates, so a pickup location cannot be represented
-- truthfully under the current schema.
--
-- The local catalog originally contained two manually-added printing entries
-- that are not in the CSV. Remove those records (and their locations) before
-- completing the seed. The historical A Hot Hideout seed was also edited
-- locally; restore its CSV identity and location values while preserving IDs.
DELETE FROM "supplier_locations"
WHERE "supplier_id" IN (
    SELECT "id" FROM "suppliers"
    WHERE "name" IN ('CLB Print Station', 'Printing@CLB')
);

DELETE FROM "suppliers"
WHERE "name" IN ('CLB Print Station', 'Printing@CLB');

